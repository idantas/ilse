// Inlines src/react/sounds/*.mp3 into src/react/sound-data.ts: run after replacing a sound.
import { readFileSync, writeFileSync } from 'node:fs';

const uri = (file) => 'data:audio/mpeg;base64,' + readFileSync(new URL(`../src/react/sounds/${file}`, import.meta.url)).toString('base64');
writeFileSync(new URL('../src/react/sound-data.ts', import.meta.url), `// Generated by scripts/sound-data.mjs from src/react/sounds/*.mp3 — don't edit. Inlined so every way
// the toolbar loads (proxy, Vite plugin, extension, bookmarklet) has them, with no file to serve.
export const DONE_MP3 = ${JSON.stringify(uri('done.mp3'))};
export const ATTENTION_MP3 = ${JSON.stringify(uri('attention.mp3'))};
`);
